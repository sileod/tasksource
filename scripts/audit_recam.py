"""Verify the Hub ReCAM copy and regenerate its native-test article exclusions.

    python scripts/audit_recam.py

Keep usable Hub data direct. The original unlabeled test shares articles with
training/development; this small manifest protects those articles without
shipping another copy of the dataset or downloading test data at task load.
"""
import csv
import hashlib
import io
import json
from pathlib import Path
from urllib.request import urlopen

SOURCE = 'boyuanzheng010/SemEval2021-Reading-Comprehension-of-Abstract-Meaning'
REVISION = '93dff63af52d031980da8a8c8ea71f5a399031dc'
HUB_REVISION = '1061da9ff8290ae64d2ab4659eccd5c78407ff13'
ROOT = Path(__file__).resolve().parents[1]


def article_key(text):
    return hashlib.sha256(' '.join(text.casefold().split()).encode()).hexdigest()


def main():
    labeled=set();heldout=set();hashes={}
    for task in (1,2):
        for split in ('train','dev','test'):
            path=f"data/{'test_data' if split=='test' else 'training_data'}/Task_{task}_{split}.jsonl"
            with urlopen(f'https://raw.githubusercontent.com/{SOURCE}/{REVISION}/{path}',timeout=60) as r:raw=r.read()
            hashes[path]=hashlib.sha256(raw).hexdigest()
            rows=[json.loads(line) for line in raw.splitlines() if line.strip()]
            if split!='test':
                with urlopen(f'https://huggingface.co/datasets/holylovenia/recam/resolve/{HUB_REVISION}/Task_{task}_{split}.csv',timeout=60) as r:
                    copy=list(csv.DictReader(io.StringIO(r.read().decode('utf-8-sig'))))
                for row in copy:row['label']=int(row['label'])
                if rows!=copy:raise ValueError(f'Hub/native mismatch: task {task}, {split}')
            (heldout if split=='test' else labeled).update(article_key(r['article']) for r in rows)
    overlap=sorted(labeled & heldout)
    path=ROOT/'src/tasksource/metadata/recam_test_overlap.py'
    path.write_text('"""Generated by scripts/audit_recam.py; native unlabeled-test article exclusions."""\n'
        +f'SOURCE_REVISION = {REVISION!r}\nHUB_REVISION = {HUB_REVISION!r}\n'
        +'RECAM_TEST_OVERLAP = frozenset({\n'+''.join(f'    {key!r},\n' for key in overlap)+'})\n')
    print(json.dumps(dict(source=SOURCE,revision=REVISION,hub_revision=HUB_REVISION,
        verified_hub_copy=True,test_overlap_articles=len(overlap),source_sha256=hashes),indent=2))


if __name__=='__main__':main()
